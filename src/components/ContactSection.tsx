import { useEffect, useState, type FormEvent } from 'react';
import { ArrowUpRight, CheckCircle2, Mail } from 'lucide-react';
import { CONTACT_LINKS, type TopicOption } from '../data/portfolioData';
import { formatTopicPrompt, validateContactForm } from '../utils/portfolio';

interface ContactSectionProps {
  selectedTopics: TopicOption[];
}

export function ContactSection({ selectedTopics }: ContactSectionProps) {
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [message, setMessage] = useState('');
  const [errors, setErrors] = useState<{ name?: string; email?: string; message?: string }>({});
  const [submitted, setSubmitted] = useState(false);

  useEffect(() => {
    setMessage((prev) => {
      const isAutoGenerated =
        !prev.trim() || prev.startsWith("Hi Shahbaj, I'd like to connect regarding:");
      if (!isAutoGenerated) {
        return prev;
      }
      return selectedTopics.length > 0 ? formatTopicPrompt(selectedTopics) : '';
    });
  }, [selectedTopics]);

  const handleSubmit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const validation = validateContactForm({ name, email, message });
    if (!validation.valid) {
      setErrors(validation.errors);
      setSubmitted(false);
      return;
    }
    setErrors({});
    setSubmitted(true);
  };

  const mailtoHref = `mailto:${CONTACT_LINKS.email}?subject=${encodeURIComponent(
    selectedTopics.length > 0
      ? `Portfolio Inquiry: ${selectedTopics.join(', ')}`
      : 'Portfolio Inquiry'
  )}&body=${encodeURIComponent(
    `${message}\n\nFrom: ${name || 'Visitor'} (${email || 'no email provided'})`
  )}`;

  return (
    <footer
      id="contact"
      aria-labelledby="contact-heading"
      className="relative z-10 scroll-mt-20 bg-[#FAFBF9] border-t border-[#EAECE9] pt-24 pb-12"
    >
      <div className="max-w-7xl mx-auto px-6">
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-12 lg:gap-16 pb-16 border-b border-[#EAECE9]">
          <div className="lg:col-span-5 flex flex-col justify-between gap-8">
            <div>
              <p className="text-sm text-[#738273] mb-3">
                Let&apos;s Connect · Learn · Build · Collaborate
              </p>
              <h2
                id="contact-heading"
                className="text-3xl sm:text-4xl lg:text-5xl font-normal tracking-tight text-black leading-[1.12] mb-5"
              >
                Drop a message &amp; say hello.
              </h2>
              <p className="text-base text-[#5A635A] leading-relaxed max-w-md">
                {CONTACT_LINKS.locationNote}
              </p>
            </div>

            <div className="space-y-3">
              <p className="text-xs font-medium uppercase tracking-wider text-[#738273]">
                Direct Profiles
              </p>
              <div className="flex flex-wrap gap-3">
                <a
                  href={CONTACT_LINKS.github}
                  target="_blank"
                  rel="noopener noreferrer"
                  aria-label="Open Shahbaj's GitHub profile"
                  className="inline-flex items-center gap-2 px-4 py-2.5 rounded-full bg-white border border-[#EAECE9] text-sm font-medium text-[#1C2E1E] hover:border-[#1C2E1E] transition-colors whitespace-nowrap shrink-0"
                >
                  <span>GitHub</span>
                  <ArrowUpRight className="w-4 h-4 text-[#4D6D47]" aria-hidden="true" />
                </a>
                <a
                  href={CONTACT_LINKS.linkedin}
                  target="_blank"
                  rel="noopener noreferrer"
                  aria-label="Open Shahbaj's LinkedIn profile"
                  className="inline-flex items-center gap-2 px-4 py-2.5 rounded-full bg-white border border-[#EAECE9] text-sm font-medium text-[#1C2E1E] hover:border-[#1C2E1E] transition-colors whitespace-nowrap shrink-0"
                >
                  <span>LinkedIn</span>
                  <ArrowUpRight className="w-4 h-4 text-[#4D6D47]" aria-hidden="true" />
                </a>
                <a
                  href={`mailto:${CONTACT_LINKS.email}`}
                  aria-label="Email Shahbaj directly"
                  className="inline-flex items-center gap-2 px-4 py-2.5 rounded-full bg-white border border-[#EAECE9] text-sm font-medium text-[#1C2E1E] hover:border-[#1C2E1E] transition-colors whitespace-nowrap shrink-0"
                >
                  <Mail className="w-4 h-4 text-[#4D6D47]" aria-hidden="true" />
                  <span>{CONTACT_LINKS.email}</span>
                </a>
              </div>
            </div>
          </div>

          <div className="lg:col-span-7">
            <form
              onSubmit={handleSubmit}
              noValidate
              className="bg-white border border-[#EAECE9] rounded-2xl p-6 sm:p-8 space-y-5"
            >
              {selectedTopics.length > 0 && (
                <p className="text-xs text-[#4D6D47] font-medium">
                  Selected interests: {selectedTopics.join(' · ')}
                </p>
              )}

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <div>
                  <label
                    htmlFor="contact-name"
                    className="block text-sm font-medium text-[#1C2E1E] mb-1.5"
                  >
                    Name
                  </label>
                  <input
                    id="contact-name"
                    type="text"
                    value={name}
                    onChange={(e) => {
                      setName(e.target.value);
                      if (errors.name) setErrors((prev) => ({ ...prev, name: undefined }));
                    }}
                    placeholder="Your name"
                    className="w-full rounded-xl border border-[#EAECE9] bg-[#FAFBF9] px-4 py-2.5 text-sm text-black placeholder:text-neutral-400 focus:outline-none focus:border-[#1C2E1E]"
                  />
                  {errors.name && (
                    <p role="alert" className="text-xs text-rose-700 mt-1.5">
                      {errors.name}
                    </p>
                  )}
                </div>

                <div>
                  <label
                    htmlFor="contact-email"
                    className="block text-sm font-medium text-[#1C2E1E] mb-1.5"
                  >
                    Email
                  </label>
                  <input
                    id="contact-email"
                    type="email"
                    value={email}
                    onChange={(e) => {
                      setEmail(e.target.value);
                      if (errors.email) setErrors((prev) => ({ ...prev, email: undefined }));
                    }}
                    placeholder="you@example.com"
                    className="w-full rounded-xl border border-[#EAECE9] bg-[#FAFBF9] px-4 py-2.5 text-sm text-black placeholder:text-neutral-400 focus:outline-none focus:border-[#1C2E1E]"
                  />
                  {errors.email && (
                    <p role="alert" className="text-xs text-rose-700 mt-1.5">
                      {errors.email}
                    </p>
                  )}
                </div>
              </div>

              <div>
                <label
                  htmlFor="contact-message"
                  className="block text-sm font-medium text-[#1C2E1E] mb-1.5"
                >
                  Message
                </label>
                <textarea
                  id="contact-message"
                  rows={4}
                  value={message}
                  onChange={(e) => {
                    setMessage(e.target.value);
                    if (errors.message) setErrors((prev) => ({ ...prev, message: undefined }));
                  }}
                  placeholder="Share a project idea, study topic, or question..."
                  className="w-full rounded-xl border border-[#EAECE9] bg-[#FAFBF9] px-4 py-3 text-sm text-black placeholder:text-neutral-400 focus:outline-none focus:border-[#1C2E1E]"
                />
                {errors.message && (
                  <p role="alert" className="text-xs text-rose-700 mt-1.5">
                    {errors.message}
                  </p>
                )}
              </div>

              <div className="flex flex-wrap items-center justify-between gap-4 pt-1">
                <button
                  type="submit"
                  className="px-6 py-3 rounded-full bg-[#1C2E1E] text-white text-sm font-medium hover:opacity-90 transition-opacity cursor-pointer"
                >
                  Prepare Message
                </button>

                <a
                  href={mailtoHref}
                  className="text-xs font-medium text-[#4D6D47] underline underline-offset-4 hover:opacity-75 transition-opacity"
                >
                  Open in email client ↗
                </a>
              </div>

              {submitted && (
                <div
                  role="status"
                  className="rounded-xl bg-[#FAFBF9] border border-[#EAECE9] px-4 py-3 flex items-start gap-2.5 text-sm text-[#1C2E1E]"
                >
                  <CheckCircle2
                    className="w-4 h-4 text-[#4D6D47] mt-0.5 shrink-0"
                    aria-hidden="true"
                  />
                  <div>
                    <p className="font-medium">Message ready for {CONTACT_LINKS.email}</p>
                    <p className="text-xs text-[#5A635A] mt-0.5">
                      Click &ldquo;Open in email client&rdquo; above to send directly, or reach out via GitHub / LinkedIn.
                    </p>
                  </div>
                </div>
              )}
            </form>
          </div>
        </div>

        <div className="pt-8 flex flex-col sm:flex-row items-center justify-between gap-4 text-xs text-[#738273]">
          <span>{CONTACT_LINKS.copyright}</span>
          <span>B.Tech CSE · Exploring AI/ML &amp; Software Development</span>
        </div>
      </div>
    </footer>
  );
}
